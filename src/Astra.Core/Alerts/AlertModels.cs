namespace Astra.Core.Alerts;

/// <summary>How a webhook's payload is rendered (column <c>webhooks.format</c>).</summary>
public static class WebhookFormats
{
    /// <summary>Astra's own JSON, signed with an Astra-generated secret (X-Astra-Signature).</summary>
    public const string Generic = "generic";

    /// <summary>Feishu / Lark custom bot; optional signing secret (body <c>timestamp</c> + <c>sign</c>).</summary>
    public const string Feishu = "feishu";

    /// <summary>DingTalk custom robot; optional signing secret (URL <c>timestamp</c> + <c>sign</c>).</summary>
    public const string DingTalk = "dingtalk";

    /// <summary>WeCom (企业微信) group robot.</summary>
    public const string WeCom = "wecom";

    /// <summary>Slack incoming webhook.</summary>
    public const string Slack = "slack";

    /// <summary>Discord webhook.</summary>
    public const string Discord = "discord";

    public static readonly IReadOnlyList<string> All = [Generic, Feishu, DingTalk, WeCom, Slack, Discord];

    /// <summary>Formats whose secret is the user's bot secret (entered, never generated).</summary>
    public static bool UsesBotSecret(string format) => format is Feishu or DingTalk;
}

/// <summary>A delivery target (row of <c>webhooks</c>). Secrets are ISecretProtector-encrypted; the API never echoes them.</summary>
public sealed class WebhookRecord
{
    public string Id { get; set; } = "";
    public string Name { get; set; } = "";

    /// <summary>http(s) only.</summary>
    public string Url { get; set; } = "";

    /// <summary><see cref="WebhookFormats"/>.</summary>
    public string Format { get; set; } = WebhookFormats.Generic;

    /// <summary>
    /// Signing secret; null = unsigned. Generic: the HMAC key of X-Astra-Signature (generated by Astra). Feishu /
    /// DingTalk: the bot's own signing secret.
    /// </summary>
    public string? SecretEnc { get; set; }

    /// <summary>Extra request headers (JSON object, encrypted as a whole: they may carry credentials).</summary>
    public string? HeadersEnc { get; set; }

    public bool Enabled { get; set; } = true;
    public int TimeoutSec { get; set; } = 10;

    /// <summary>true = the global outbound proxy setting applies; false = always direct.</summary>
    public bool UseProxy { get; set; } = true;

    public DateTimeOffset CreatedAt { get; set; }
    public DateTimeOffset UpdatedAt { get; set; }
}

/// <summary>An alert rule (row of <c>alert_rules</c>): event + condition + subjects → webhooks.</summary>
public sealed class AlertRuleRecord
{
    public string Id { get; set; } = "";
    public string Name { get; set; } = "";
    public bool Enabled { get; set; } = true;

    /// <summary><see cref="AlertEventIds"/>.</summary>
    public string Event { get; set; } = "";

    /// <summary>JSON array of subject ids; null = every subject of the event's type.</summary>
    public string? SubjectsJson { get; set; }

    /// <summary>Normalized condition (<see cref="AlertConditions.Normalize"/>), JSON object.</summary>
    public string? ConditionJson { get; set; }

    /// <summary>Also notify (status "resolved") when the condition clears.</summary>
    public bool NotifyResolved { get; set; }

    /// <summary>Re-notify while still firing every this many minutes; null = once.</summary>
    public int? RepeatMinutes { get; set; }

    /// <summary>A new firing this soon after the last resolve is not notified (flapping).</summary>
    public int CooldownMinutes { get; set; } = 60;

    public DateTimeOffset CreatedAt { get; set; }
    public DateTimeOffset UpdatedAt { get; set; }

    /// <summary>Target webhooks (table <c>alert_rule_webhooks</c>; not a column).</summary>
    public List<string> WebhookIds { get; set; } = [];
}

public static class AlertStates
{
    public const string Firing = "firing";
    public const string Ok = "ok";
}

/// <summary>Where one rule stands for one subject (row of <c>alert_states</c>).</summary>
public sealed class AlertStateRecord
{
    public string RuleId { get; set; } = "";
    public string SubjectId { get; set; } = "";
    public string SubjectName { get; set; } = "";
    public string State { get; set; } = AlertStates.Ok;

    /// <summary>The last observed figures (JSON object).</summary>
    public string? ValueJson { get; set; }

    public DateTimeOffset ChangedAt { get; set; }
    public DateTimeOffset? LastNotifiedAt { get; set; }
}

public static class WebhookDeliveryStatus
{
    public const string Pending = "pending";
    public const string Success = "success";
    public const string Failed = "failed";
}

/// <summary>One webhook call and its retries (row of <c>webhook_deliveries</c>).</summary>
public sealed class WebhookDeliveryRecord
{
    /// <summary>ULID; also the X-Astra-Delivery header.</summary>
    public string Id { get; set; } = "";

    public string WebhookId { get; set; } = "";

    /// <summary>null = a test delivery.</summary>
    public string? RuleId { get; set; }

    public string Event { get; set; } = "";
    public string Status { get; set; } = WebhookDeliveryStatus.Pending;
    public int Attempts { get; set; }
    public DateTimeOffset? NextAttemptAt { get; set; }
    public int? HttpStatus { get; set; }
    public string? Error { get; set; }

    /// <summary>The start of the response body (at most 2 KB).</summary>
    public string? ResponseSnippet { get; set; }

    public string PayloadJson { get; set; } = "{}";
    public DateTimeOffset CreatedAt { get; set; }
    public DateTimeOffset? FinishedAt { get; set; }
}
