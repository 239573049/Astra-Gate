using System.Text.Json.Nodes;
using Astra.Api.Contracts;

namespace Astra.Desktop.Core.Settings;

/// <summary>One custom header of a webhook form: a stored one shows "kept" until a new value is typed.</summary>
public sealed class HeaderDraft(string name, string value, bool stored)
{
    /// <summary>Header name.</summary>
    public string Name { get; set; } = name;

    /// <summary>Header value (blank for a stored header keeps the stored value).</summary>
    public string Value { get; set; } = value;

    /// <summary>The header already exists on the server (its value is never sent back).</summary>
    public bool Stored { get; } = stored;
}

/// <summary>
/// The webhook editor's state (web NotificationSettings <c>WebhookSheet</c>): which fields show for which format, and the create / update
/// bodies. A secret is only ever sent when typed; a generic webhook's secret is generated by the server and shown once.
/// </summary>
public sealed class WebhookDraft
{
    /// <summary>The platforms, in the web's order.</summary>
    public static readonly string[] Formats = ["generic", "feishu", "dingtalk", "wecom", "slack", "discord"];

    private readonly WebhookDto? _hook;

    /// <summary>Starts a form for <paramref name="hook"/>; null = a new webhook.</summary>
    public WebhookDraft(WebhookDto? hook)
    {
        _hook = hook;
        Name = hook?.Name ?? "";
        Url = hook?.Url ?? "";
        TimeoutSec = hook?.TimeoutSec ?? 10;
        UseProxy = hook?.UseProxy ?? true;
        Enabled = hook?.Enabled ?? true;
        Signed = hook is null || hook.HasSecret;
        Format = hook?.Format ?? "generic";
        foreach (var n in hook?.HeaderNames ?? []) Headers.Add(new HeaderDraft(n, "", true));
    }

    /// <summary>Whether the form creates a webhook.</summary>
    public bool IsNew => _hook is null;

    /// <summary>The webhook being edited, if any.</summary>
    public WebhookDto? Hook => _hook;

    /// <summary>Display name.</summary>
    public string Name { get; set; }

    /// <summary>Target address.</summary>
    public string Url { get; set; }

    /// <summary>Delivery timeout in seconds; null while the field is empty.</summary>
    public decimal? TimeoutSec { get; set; }

    /// <summary>Send through the outbound proxy.</summary>
    public bool UseProxy { get; set; }

    /// <summary>Delivering at all.</summary>
    public bool Enabled { get; set; }

    /// <summary>Signed with a secret.</summary>
    public bool Signed { get; set; }

    /// <summary>The platform.</summary>
    public string Format { get; private set; }

    /// <summary>The bot's own signing secret (feishu / dingtalk).</summary>
    public string BotSecret { get; set; } = "";

    /// <summary>Custom headers.</summary>
    public List<HeaderDraft> Headers { get; } = [];

    /// <summary>Formats whose secret is the bot's own signing secret, entered by the user.</summary>
    public static bool UsesBotSecret(string format) => format is "feishu" or "dingtalk";

    /// <summary>Where each platform's bot address comes from (placeholder only).</summary>
    public static string UrlExample(string format) => format switch
    {
        "feishu" => "https://open.feishu.cn/open-apis/bot/v2/hook/…",
        "dingtalk" => "https://oapi.dingtalk.com/robot/send?access_token=…",
        "wecom" => "https://qyapi.weixin.qq.com/cgi-bin/webhook/send?key=…",
        "slack" => "https://hooks.slack.com/services/…",
        "discord" => "https://discord.com/api/webhooks/…",
        _ => "https://",
    };

    /// <summary>The catalog key of a format's name.</summary>
    public static Msg FormatLabel(string format) => new("alerts.webhooks.format." + format);

    /// <summary>The catalog key of a format's hint.</summary>
    public static Msg FormatHint(string format) => new("alerts.webhooks.format." + format + ".hint");

    /// <summary>Changes the platform; the signed switch follows (generic and bot formats default to signed, a kept secret stays).</summary>
    public void ChangeFormat(string format)
    {
        Format = format;
        Signed = format == "generic" || (_hook is not null && _hook.Format == format && _hook.HasSecret) || UsesBotSecret(format);
    }

    /// <summary>Whether the bot-secret field shows.</summary>
    public bool BotSecretVisible => UsesBotSecret(Format) && Signed;

    /// <summary>The bot-secret placeholder: "kept" when the stored secret stays.</summary>
    public Msg? BotSecretKept => _hook is not null && _hook.Format == Format && _hook.HasSecret ? new Msg("alerts.webhooks.headerKept") : null;

    /// <summary>Whether the signed switch shows: a generic webhook offers it for new ones and ones with a secret; bots always.</summary>
    public bool SignedVisible => Format == "generic" ? IsNew || (_hook is { Format: "generic", HasSecret: true }) : UsesBotSecret(Format);

    /// <summary>The signed switch's detail.</summary>
    public Msg SignedHint => new(Format == "generic" ? "alerts.webhooks.signedHint" : "alerts.webhooks.botSignedHint");

    /// <summary>Whether Save is enabled.</summary>
    public bool CanSave => Name.Trim() != "" && Url.Trim() != "";

    private JsonObject CommonBody()
    {
        var headers = Headers.Where(h => h.Name.Trim() != "").ToList();
        JsonNode? headerNode = null;
        if (headers.Count > 0)
        {
            var o = new JsonObject();
            foreach (var h in headers) o[h.Name.Trim()] = h.Value;
            headerNode = o;
        }
        return JsonPatch.Of(
            ("name", Name.Trim()), ("url", Url.Trim()), ("timeoutSec", (int)(TimeoutSec ?? 10)), ("useProxy", UseProxy), ("enabled", Enabled),
            ("headers", headerNode));
    }

    /// <summary>A bot format's secret choice: unsigned clears it (""), a typed one replaces it, empty keeps it (null = not sent).</summary>
    private string? BotSecretField => !UsesBotSecret(Format) ? null : !Signed ? "" : BotSecret.Trim() is { Length: > 0 } s ? s : null;

    /// <summary>The POST body of a new webhook.</summary>
    public JsonObject CreateBody()
    {
        var o = CommonBody();
        o["format"] = Format;
        if (Format == "generic") o["signed"] = Signed;
        else if (BotSecretField is { } secret) o["secret"] = secret;
        return o;
    }

    /// <summary>The PATCH body of an existing webhook.</summary>
    public JsonObject UpdateBody()
    {
        var hook = _hook ?? throw new InvalidOperationException("a new webhook has no update body");
        var o = CommonBody();
        var formatChanged = hook.Format != Format;
        if (formatChanged) o["format"] = Format;
        if (Format == "generic")
        {
            if (!(Signed || !hook.HasSecret || formatChanged)) o["signed"] = false;
        }
        else if (BotSecretField is { } secret) o["secret"] = secret;
        return o;
    }
}

/// <summary>Everything the notification rows and the delivery list say about a webhook or a delivery.</summary>
public static class WebhookLogic
{
    /// <summary>The badges after a webhook's name: disabled / non-generic format / unsigned.</summary>
    public static IReadOnlyList<(Msg Text, string Tone)> Badges(WebhookDto hook)
    {
        var list = new List<(Msg, string)>();
        if (!hook.Enabled) list.Add((new Msg("alerts.webhooks.disabledBadge"), "orange"));
        if (hook.Format != "generic") list.Add((WebhookDraft.FormatLabel(hook.Format), "accent"));
        if (!hook.HasSecret && (hook.Format == "generic" || WebhookDraft.UsesBotSecret(hook.Format))) list.Add((new Msg("alerts.webhooks.unsigned"), "neutral"));
        return list;
    }

    /// <summary>The toast of a test delivery.</summary>
    public static ToastMsg TestToast(WebhookDeliveryDto d)
        => d.Status == "success"
            ? new ToastMsg(Msg.Of("alerts.webhooks.testOk", ("status", d.HttpStatus?.ToString() ?? "")))
            : new ToastMsg(Msg.Of("alerts.webhooks.testFailed", ("error", d.Error ?? d.Status)), true);

    /// <summary>The tone of a delivery's status badge.</summary>
    public static string StatusTone(string status) => status switch { "success" => "green", "pending" => "orange", _ => "red" };

    /// <summary>The event name of a delivery: a test or the alert event's name.</summary>
    public static Msg EventName(string evt) => evt == "test" ? new Msg("alerts.webhooks.test") : AlertLogic.EventName(evt);

    /// <summary>The "HTTP 200 error" fragment of a delivery's summary.</summary>
    public static string Outcome(WebhookDeliveryDto d)
        => $"{(d.HttpStatus is { } h && h != 0 ? $"HTTP {h}" : "")} {(d.Error is { Length: > 0 } e && d.Status != "success" ? e : "")}".Trim();

    /// <summary>The attempts / next attempt fragment.</summary>
    public static Msg Attempts(WebhookDeliveryDto d, string language)
        => d.Status == "pending" && d.NextAttemptAt is { } next
            ? Msg.Of("alerts.delivery.next", ("time", SettingsFormat.DateTime(next, language)))
            : Msg.Of("alerts.delivery.attempts", ("count", d.Attempts));
}
