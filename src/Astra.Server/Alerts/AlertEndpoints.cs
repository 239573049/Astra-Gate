using System.Text.Json.Nodes;
using Astra.Core;
using Astra.Core.Alerts;
using Astra.Core.Clients;
using Astra.Data;
using Astra.Gateway.Pipeline;
using Astra.Server.Api;

namespace Astra.Server.Alerts;








/// <summary>Admin side of alerts (plan: alerts-webhooks-token-limits §5): webhooks, rules, states and deliveries.</summary>
public sealed class AlertService(AstraDatabase db, ISecretProtector secrets, AlertEngine engine, WebhookDispatcher dispatcher,
    SettingsService settings, Hosting.ServerOptions server)
{
    private const int MaxName = 64;
    private const int MaxRepeatMinutes = 7 * 24 * 60;

    /// <summary>Headers the dispatcher sets itself (or the HTTP stack owns): never taken from the user.</summary>
    private static readonly string[] ReservedHeaders = ["content-type", "content-length", "host", "user-agent", "transfer-encoding", "connection"];

    // ------------------------------------------------------------------ webhooks

    public async Task<List<WebhookDto>> ListWebhooksAsync(CancellationToken ct) =>
        (await db.Alerts.ListWebhooksAsync(ct)).Select(ToDto).ToList();

    public async Task<WebhookSecretDto> CreateWebhookAsync(JsonObject body, CancellationToken ct)
    {
        var now = DateTimeOffset.UtcNow;
        var hook = new WebhookRecord
        {
            Id = Ulid.NewUlid(),
            Name = RequireName(Str(body, "name")),
            Url = RequireUrl(Str(body, "url")),
            Format = Format(body) ?? WebhookFormats.Generic,
            Enabled = Bool(body, "enabled") ?? true,
            TimeoutSec = Timeout(body) ?? 10,
            UseProxy = Bool(body, "useProxy") ?? true,
            CreatedAt = now,
            UpdatedAt = now,
        };
        hook.HeadersEnc = Headers(body["headers"], []);
        string? secret = null;
        if (hook.Format == WebhookFormats.Generic)
        {
            if (body.ContainsKey("secret")) throw new AdminApiException(400, "a generic webhook's secret is generated by Astra");
            if (Bool(body, "signed") ?? true)
            {
                secret = WebhookDispatcher.NewSecret();
                hook.SecretEnc = secrets.Protect(secret);
            }
        }
        else
            ApplyBotSecret(hook, body);
        await db.Alerts.InsertWebhookAsync(hook, ct);
        engine.Invalidate();
        return new WebhookSecretDto(ToDto(hook), secret);
    }

    /// <summary>
    /// Patch: <c>name</c>, <c>url</c>, <c>format</c> (a change drops the secret: it belongs to the old format),
    /// <c>enabled</c>, <c>timeoutSec</c>, <c>useProxy</c>, <c>headers</c> (an object that replaces the set: an empty
    /// value keeps that header's current value; null clears all), <c>secret</c> (Feishu / DingTalk: the bot's signing
    /// secret; "" or null clears it), <c>signed: false</c> drops the secret (generic: re-sign with <c>/secret</c>).
    /// </summary>
    public async Task<WebhookDto> UpdateWebhookAsync(string id, JsonObject body, CancellationToken ct)
    {
        var hook = await RequireWebhookAsync(id, ct);
        if (body.ContainsKey("name")) hook.Name = RequireName(Str(body, "name"));
        if (body.ContainsKey("url")) hook.Url = RequireUrl(Str(body, "url"));
        if (Format(body) is { } format && format != hook.Format)
        {
            hook.Format = format;
            hook.SecretEnc = null;
        }
        if (body.ContainsKey("secret"))
        {
            if (hook.Format == WebhookFormats.Generic) throw new AdminApiException(400, "a generic webhook's secret is generated by Astra");
            ApplyBotSecret(hook, body);
        }
        if (Bool(body, "enabled") is { } enabled) hook.Enabled = enabled;
        if (Timeout(body) is { } timeout) hook.TimeoutSec = timeout;
        if (Bool(body, "useProxy") is { } useProxy) hook.UseProxy = useProxy;
        if (body.ContainsKey("headers")) hook.HeadersEnc = Headers(body["headers"], dispatcher.CustomHeaders(hook));
        if (Bool(body, "signed") == false) hook.SecretEnc = null;
        hook.UpdatedAt = DateTimeOffset.UtcNow;
        await db.Alerts.UpdateWebhookAsync(hook, ct);
        return ToDto(hook);
    }

    public async Task<WebhookSecretDto> ResetSecretAsync(string id, CancellationToken ct)
    {
        var hook = await RequireWebhookAsync(id, ct);
        if (hook.Format != WebhookFormats.Generic) throw new AdminApiException(400, "only generic webhooks have a generated secret");
        var secret = WebhookDispatcher.NewSecret();
        hook.SecretEnc = secrets.Protect(secret);
        hook.UpdatedAt = DateTimeOffset.UtcNow;
        await db.Alerts.UpdateWebhookAsync(hook, ct);
        return new WebhookSecretDto(ToDto(hook), secret);
    }

    public async Task DeleteWebhookAsync(string id, CancellationToken ct)
    {
        if (!await db.Alerts.DeleteWebhookAsync(id, ct)) throw new AdminApiException(404, "Webhook not found");
        engine.Invalidate();
    }

    /// <summary>Sends a <c>test</c> event once (no retries) and returns the outcome.</summary>
    public async Task<WebhookDeliveryDto> TestAsync(string id, CancellationToken ct)
    {
        var hook = await RequireWebhookAsync(id, ct);
        var now = DateTimeOffset.UtcNow;
        var deliveryId = Ulid.NewUlid();
        var s = settings.Current;
        var delivery = new WebhookDeliveryRecord
        {
            Id = deliveryId,
            WebhookId = hook.Id,
            Event = AlertEventIds.Test,
            PayloadJson = WebhookDispatcher.Payload(deliveryId, AlertEventIds.Test, "test", false, now, null, "test", "test", "Astra",
                [], [], AlertMessages.Format(s.Locale, AlertEventIds.Test, "test", "Astra", [], []), server.GatewayBaseUrl),
            CreatedAt = now,
        };
        await db.Alerts.InsertDeliveryAsync(delivery, ct);
        // A test of a disabled webhook still goes out: the user asked for it explicitly.
        var sent = await dispatcher.AttemptAsync(delivery, ForTest(hook), retry: false, ct);
        return ToDto(sent);
    }

    private static WebhookRecord ForTest(WebhookRecord hook) => new()
    {
        Id = hook.Id, Name = hook.Name, Url = hook.Url, Format = hook.Format, SecretEnc = hook.SecretEnc, HeadersEnc = hook.HeadersEnc,
        Enabled = true, TimeoutSec = hook.TimeoutSec, UseProxy = hook.UseProxy,
    };

    public async Task<List<WebhookDeliveryDto>> DeliveriesAsync(string id, int limit, CancellationToken ct)
    {
        await RequireWebhookAsync(id, ct);
        return (await db.Alerts.ListDeliveriesAsync(id, Math.Clamp(limit, 1, 200), ct)).Select(ToDto).ToList();
    }

    /// <summary>Queues a copy of a delivery (new id, same payload) for sending now.</summary>
    public async Task<WebhookDeliveryDto> RedeliverAsync(string deliveryId, CancellationToken ct)
    {
        var original = await db.Alerts.GetDeliveryAsync(deliveryId, ct) ?? throw new AdminApiException(404, "Delivery not found");
        var id = Ulid.NewUlid();
        var payload = JsonNode.Parse(original.PayloadJson) as JsonObject ?? [];
        payload["id"] = id;
        var copy = new WebhookDeliveryRecord
        {
            Id = id,
            WebhookId = original.WebhookId,
            RuleId = original.RuleId,
            Event = original.Event,
            PayloadJson = payload.ToJsonString(Gateway.Protocol.GatewayJson.Options),
            CreatedAt = DateTimeOffset.UtcNow,
        };
        await db.Alerts.InsertDeliveryAsync(copy, ct);
        dispatcher.Wake();
        return ToDto(copy);
    }

    // ------------------------------------------------------------------ rules

    public static List<AlertEventDto> Events() => AlertEvents.All
        .Select(e => new AlertEventDto(e.Id, e.SubjectType,
            e.Params.Select(p => new AlertParamDto(p.Name, p.Kind, p.Choices?.ToList(), p.Default, p.Required)).ToList()))
        .ToList();

    public async Task<List<AlertRuleDto>> ListRulesAsync(CancellationToken ct)
    {
        var states = await db.Alerts.ListStatesAsync(ct);
        return (await db.Alerts.ListRulesAsync(ct))
            .Select(r => ToDto(r, states.Count(s => s.RuleId == r.Id && s.State == AlertStates.Firing)))
            .ToList();
    }

    public async Task<AlertRuleDto> CreateRuleAsync(JsonObject body, CancellationToken ct)
    {
        var now = DateTimeOffset.UtcNow;
        var rule = new AlertRuleRecord { Id = Ulid.NewUlid(), CreatedAt = now, UpdatedAt = now };
        await ApplyRuleAsync(rule, body, creating: true, ct);
        await db.Alerts.InsertRuleAsync(rule, ct);
        engine.Invalidate();
        return ToDto(rule, 0);
    }

    public async Task<AlertRuleDto> UpdateRuleAsync(string id, JsonObject body, CancellationToken ct)
    {
        var rule = await db.Alerts.GetRuleAsync(id, ct) ?? throw new AdminApiException(404, "Alert rule not found");
        var before = (rule.Event, rule.ConditionJson, rule.SubjectsJson);
        await ApplyRuleAsync(rule, body, creating: false, ct);
        rule.UpdatedAt = DateTimeOffset.UtcNow;
        // What fires changed: start over (a condition that holds right away notifies again).
        await db.Alerts.UpdateRuleAsync(rule, resetStates: before != (rule.Event, rule.ConditionJson, rule.SubjectsJson), ct);
        engine.Invalidate();
        return (await ListRulesAsync(ct)).First(r => r.Id == id);
    }

    public async Task DeleteRuleAsync(string id, CancellationToken ct)
    {
        if (!await db.Alerts.DeleteRuleAsync(id, ct)) throw new AdminApiException(404, "Alert rule not found");
        engine.Invalidate();
    }

    public async Task<List<AlertStateDto>> StatesAsync(bool firingOnly, CancellationToken ct)
    {
        var rules = (await db.Alerts.ListRulesAsync(ct)).ToDictionary(r => r.Id);
        return (await db.Alerts.ListStatesAsync(ct))
            .Where(s => !firingOnly || s.State == AlertStates.Firing)
            .Where(s => rules.ContainsKey(s.RuleId))
            .Select(s =>
            {
                var rule = rules[s.RuleId];
                return new AlertStateDto(s.RuleId, rule.Name, rule.Event, AlertEvents.Find(rule.Event)?.SubjectType ?? "", s.SubjectId,
                    s.SubjectName, s.State, s.ValueJson is null ? null : JsonNode.Parse(s.ValueJson) as JsonObject, s.ChangedAt, s.LastNotifiedAt);
            })
            .ToList();
    }

    private async Task ApplyRuleAsync(AlertRuleRecord rule, JsonObject body, bool creating, CancellationToken ct)
    {
        if (creating || body.ContainsKey("name")) rule.Name = RequireName(Str(body, "name"));
        if (creating || body.ContainsKey("event"))
        {
            var eventId = Str(body, "event");
            if (eventId is null || AlertEvents.Find(eventId) is null) throw new AdminApiException(400, $"unknown event {eventId}");
            rule.Event = eventId;
        }
        if (creating || body.ContainsKey("condition") || body.ContainsKey("event"))
        {
            var condition = body.ContainsKey("condition")
                ? body["condition"] as JsonObject ?? (body["condition"] is null ? null : throw new AdminApiException(400, "condition must be an object"))
                : rule.ConditionJson is null ? null : JsonNode.Parse(rule.ConditionJson) as JsonObject;
            try
            {
                rule.ConditionJson = AlertConditions.Normalize(rule.Event, condition).ToJsonString();
            }
            catch (ArgumentException e)
            {
                throw new AdminApiException(400, e.Message);
            }
        }
        if (body.ContainsKey("subjects"))
            rule.SubjectsJson = body["subjects"] is null ? null : Json.Serialize(Strings(body["subjects"], "subjects"));
        if (body.ContainsKey("webhookIds"))
        {
            var ids = Strings(body["webhookIds"], "webhookIds");
            var known = (await db.Alerts.ListWebhooksAsync(ct)).Select(w => w.Id).ToHashSet();
            if (ids.FirstOrDefault(i => !known.Contains(i)) is { } missing) throw new AdminApiException(400, $"unknown webhook {missing}");
            rule.WebhookIds = ids;
        }
        if (Bool(body, "enabled") is { } enabled) rule.Enabled = enabled;
        if (Bool(body, "notifyResolved") is { } resolved) rule.NotifyResolved = resolved;
        if (body.ContainsKey("repeatMinutes"))
            rule.RepeatMinutes = Int(body, "repeatMinutes") is { } repeat
                ? repeat is >= 1 and <= MaxRepeatMinutes ? repeat : throw new AdminApiException(400, $"repeatMinutes must be 1–{MaxRepeatMinutes} or null")
                : null;
        if (Int(body, "cooldownMinutes") is { } cooldown)
            rule.CooldownMinutes = cooldown is >= 0 and <= MaxRepeatMinutes ? cooldown : throw new AdminApiException(400, $"cooldownMinutes must be 0–{MaxRepeatMinutes}");
    }

    // ------------------------------------------------------------------ helpers

    private async Task<WebhookRecord> RequireWebhookAsync(string id, CancellationToken ct) =>
        await db.Alerts.GetWebhookAsync(id, ct) ?? throw new AdminApiException(404, "Webhook not found");

    private WebhookDto ToDto(WebhookRecord w) => new(w.Id, w.Name, w.Url, w.Format, w.Enabled, w.TimeoutSec, w.UseProxy, w.SecretEnc is not null,
        dispatcher.CustomHeaders(w).Keys.Order(StringComparer.OrdinalIgnoreCase).ToList(), w.CreatedAt, w.UpdatedAt);

    private static WebhookDeliveryDto ToDto(WebhookDeliveryRecord d) => new(d.Id, d.WebhookId, d.RuleId, d.Event, d.Status, d.Attempts,
        d.NextAttemptAt, d.HttpStatus, d.Error, d.ResponseSnippet, Parse(d.PayloadJson), d.CreatedAt, d.FinishedAt);

    private static AlertRuleDto ToDto(AlertRuleRecord r, int firing) => new(r.Id, r.Name, r.Enabled, r.Event,
        r.SubjectsJson is null ? null : Json.Deserialize<List<string>>(r.SubjectsJson),
        r.ConditionJson is null ? [] : JsonNode.Parse(r.ConditionJson) as JsonObject ?? [], r.NotifyResolved, r.RepeatMinutes,
        r.CooldownMinutes, r.WebhookIds, firing, r.CreatedAt, r.UpdatedAt);

    private static JsonNode? Parse(string json)
    {
        try
        {
            return JsonNode.Parse(json);
        }
        catch (System.Text.Json.JsonException)
        {
            return null;
        }
    }

    /// <summary>The encrypted custom-header set from a body field; an empty value keeps <paramref name="current"/>'s value.</summary>
    private string? Headers(JsonNode? node, Dictionary<string, string> current)
    {
        if (node is null) return null;
        if (node is not JsonObject obj) throw new AdminApiException(400, "headers must be an object of name → value");
        var headers = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        foreach (var (rawName, rawValue) in obj)
        {
            var name = rawName.Trim();
            if (name.Length == 0 || name.Any(c => c <= ' ' || c == ':' || c > '~'))
                throw new AdminApiException(400, $"invalid header name {rawName}");
            if (ReservedHeaders.Contains(name.ToLowerInvariant()) || name.StartsWith("x-astra-", StringComparison.OrdinalIgnoreCase))
                throw new AdminApiException(400, $"header {name} is set by Astra");
            var value = rawValue is JsonValue v && v.TryGetValue<string>(out var s) ? s.Trim() : "";
            if (value.Any(c => c is '\r' or '\n')) throw new AdminApiException(400, $"invalid value for header {name}");
            if (value.Length == 0)
            {
                var kept = current.FirstOrDefault(h => string.Equals(h.Key, name, StringComparison.OrdinalIgnoreCase)).Value;
                if (kept is null) throw new AdminApiException(400, $"header {name} needs a value");
                value = kept;
            }
            headers[name] = value;
        }
        return headers.Count == 0 ? null : secrets.Protect(Json.Serialize(headers));
    }

    private static string? Format(JsonObject body) => Str(body, "format") is { } format
        ? WebhookFormats.All.Contains(format) ? format : throw new AdminApiException(400, $"format must be one of {string.Join(", ", WebhookFormats.All)}")
        : null;

    /// <summary>Feishu / DingTalk: the bot's signing secret from <c>secret</c> (absent / "" / null = unsigned); others have none.</summary>
    private void ApplyBotSecret(WebhookRecord hook, JsonObject body)
    {
        var secret = Str(body, "secret")?.Trim();
        if (!WebhookFormats.UsesBotSecret(hook.Format))
        {
            if (!string.IsNullOrEmpty(secret)) throw new AdminApiException(400, $"{hook.Format} webhooks are not signed");
            hook.SecretEnc = null;
            return;
        }
        if (body.ContainsKey("secret")) hook.SecretEnc = string.IsNullOrEmpty(secret) ? null : secrets.Protect(secret);
    }

    private static string RequireName(string? name)
    {
        var trimmed = name?.Trim();
        if (string.IsNullOrEmpty(trimmed)) throw new AdminApiException(400, "name is required");
        if (trimmed.Length > MaxName) throw new AdminApiException(400, $"name must be at most {MaxName} characters");
        return trimmed;
    }

    private static string RequireUrl(string? url)
    {
        var trimmed = url?.Trim();
        if (!Uri.TryCreate(trimmed, UriKind.Absolute, out var uri) || uri.Scheme is not ("http" or "https") || uri.Host.Length == 0)
            throw new AdminApiException(400, "url must be an http(s) address");
        return trimmed!;
    }

    private static int? Timeout(JsonObject body) => Int(body, "timeoutSec") is { } t
        ? t is >= 1 and <= 60 ? t : throw new AdminApiException(400, "timeoutSec must be 1–60")
        : null;

    private static string? Str(JsonObject body, string name) => body[name] switch
    {
        null => null,
        JsonValue v when v.TryGetValue<string>(out var s) => s,
        _ => throw new AdminApiException(400, $"{name} must be a string"),
    };

    private static bool? Bool(JsonObject body, string name) => body[name] switch
    {
        null => null,
        JsonValue v when v.TryGetValue<bool>(out var b) => b,
        _ => throw new AdminApiException(400, $"{name} must be a boolean"),
    };

    private static int? Int(JsonObject body, string name) => body[name] switch
    {
        null => null,
        JsonValue v when v.TryGetValue<int>(out var i) => i,
        JsonValue v when v.TryGetValue<double>(out var d) && d == Math.Floor(d) && d is >= int.MinValue and <= int.MaxValue => (int)d,
        _ => throw new AdminApiException(400, $"{name} must be an integer"),
    };

    private static List<string> Strings(JsonNode? node, string name)
    {
        if (node is not JsonArray array) throw new AdminApiException(400, $"{name} must be an array of strings");
        var list = new List<string>();
        foreach (var item in array)
        {
            if (item is not JsonValue v || !v.TryGetValue<string>(out var s) || string.IsNullOrWhiteSpace(s))
                throw new AdminApiException(400, $"{name} must be an array of strings");
            if (!list.Contains(s)) list.Add(s);
        }
        return list;
    }
}

/// <summary>/api/webhooks and /api/alerts (plan: alerts-webhooks-token-limits §5).</summary>
public static class AlertEndpoints
{
    public static void MapAlertEndpoints(this IEndpointRouteBuilder app)
    {
        var hooks = app.MapGroup("/api/webhooks").AddEndpointFilter<AdminApiErrorFilter>();
        hooks.MapGet("", async (AlertService s, CancellationToken ct) => Results.Ok(await s.ListWebhooksAsync(ct)));
        hooks.MapPost("", async (JsonObject body, AlertService s, CancellationToken ct) => Results.Ok(await s.CreateWebhookAsync(body, ct)));
        hooks.MapPatch("/{id}", async (string id, JsonObject body, AlertService s, CancellationToken ct) =>
            Results.Ok(await s.UpdateWebhookAsync(id, body, ct)));
        hooks.MapDelete("/{id}", async (string id, AlertService s, CancellationToken ct) =>
        {
            await s.DeleteWebhookAsync(id, ct);
            return Results.NoContent();
        });
        hooks.MapPost("/{id}/secret", async (string id, AlertService s, CancellationToken ct) => Results.Ok(await s.ResetSecretAsync(id, ct)));
        hooks.MapPost("/{id}/test", async (string id, AlertService s, CancellationToken ct) => Results.Ok(await s.TestAsync(id, ct)));
        hooks.MapGet("/{id}/deliveries", async (string id, int? limit, AlertService s, CancellationToken ct) =>
            Results.Ok(await s.DeliveriesAsync(id, limit ?? 50, ct)));
        app.MapPost("/api/webhook-deliveries/{id}/redeliver", async (string id, AlertService s, CancellationToken ct) =>
            Results.Ok(await s.RedeliverAsync(id, ct))).AddEndpointFilter<AdminApiErrorFilter>();

        var alerts = app.MapGroup("/api/alerts").AddEndpointFilter<AdminApiErrorFilter>();
        alerts.MapGet("/events", () => Results.Ok(AlertService.Events()));
        alerts.MapGet("/rules", async (AlertService s, CancellationToken ct) => Results.Ok(await s.ListRulesAsync(ct)));
        alerts.MapPost("/rules", async (JsonObject body, AlertService s, CancellationToken ct) => Results.Ok(await s.CreateRuleAsync(body, ct)));
        alerts.MapPatch("/rules/{id}", async (string id, JsonObject body, AlertService s, CancellationToken ct) =>
            Results.Ok(await s.UpdateRuleAsync(id, body, ct)));
        alerts.MapDelete("/rules/{id}", async (string id, AlertService s, CancellationToken ct) =>
        {
            await s.DeleteRuleAsync(id, ct);
            return Results.NoContent();
        });
        alerts.MapGet("/states", async (bool? firing, AlertService s, CancellationToken ct) => Results.Ok(await s.StatesAsync(firing ?? false, ct)));
    }
}
