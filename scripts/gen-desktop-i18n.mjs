#!/usr/bin/env node
// Generates src/Astra.Desktop.Core/I18n/Messages.g.cs from web/src/i18n/messages.ts, the only
// source of UI strings (.plan/avalonia-client.md D4 / §16). `--check` exits 1 when the checked-in
// file differs from what this would write. Uses the repo's existing esbuild; adds no dependency.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'web/src/i18n/messages.ts');
const target = join(root, 'src/Astra.Desktop.Core/I18n/Messages.g.cs');
const check = process.argv.includes('--check');

function findEsbuild() {
  const exe = process.platform === 'win32' ? 'esbuild.cmd' : 'esbuild';
  for (const dir of ['node_modules/.bin', 'web/node_modules/.bin', 'cli/node_modules/.bin']) {
    const p = join(root, dir, exe);
    if (existsSync(p)) return p;
  }
  throw new Error('esbuild not found; run `pnpm install` first');
}

async function load() {
  const js = execFileSync(findEsbuild(), [source, '--format=esm', '--platform=node', '--log-level=error'], {
    encoding: 'utf8',
    maxBuffer: 256 * 1024 * 1024,
    shell: process.platform === 'win32',
  });
  const url = 'data:text/javascript;base64,' + Buffer.from(js).toString('base64');
  return import(url);
}

function lit(s) {
  let out = '"';
  for (const ch of s) {
    const c = ch.codePointAt(0);
    if (ch === '"') out += '\\"';
    else if (ch === '\\') out += '\\\\';
    else if (ch === '\n') out += '\\n';
    else if (ch === '\r') out += '\\r';
    else if (ch === '\t') out += '\\t';
    else if (c < 0x20 || c === 0x7f || c === 0x2028 || c === 0x2029 || (c >= 0x80 && c < 0xa0))
      out += '\\u' + c.toString(16).padStart(4, '0');
    else out += ch;
  }
  return out + '"';
}

const { zh, en } = await load();
const keys = Object.keys(zh);
const missing = keys.filter((k) => typeof en[k] !== 'string');
const extra = Object.keys(en).filter((k) => !(k in zh));
if (missing.length || extra.length) {
  console.error(`zh/en key mismatch. missing in en: ${missing.join(', ')}; extra in en: ${extra.join(', ')}`);
  process.exit(1);
}

const lines = [];
lines.push('// <auto-generated>');
lines.push('// Generated by scripts/gen-desktop-i18n.mjs from web/src/i18n/messages.ts. Do not edit by hand;');
lines.push('// run `node scripts/gen-desktop-i18n.mjs` after changing messages.ts.');
lines.push('// </auto-generated>');
lines.push('#nullable enable');
lines.push('');
lines.push('namespace Astra.Desktop.Core.I18n;');
lines.push('');
lines.push('internal static class Messages');
lines.push('{');
lines.push('    /// <summary>Every key, in the order of the web zh catalog.</summary>');
lines.push('    internal static readonly string[] Keys =');
lines.push('    [');
for (const k of keys) lines.push(`        ${lit(k)},`);
lines.push('    ];');
for (const [name, cat] of [['Zh', zh], ['En', en]]) {
  lines.push('');
  lines.push(`    internal static string? ${name}(string key)`);
  lines.push('    {');
  lines.push('        switch (key)');
  lines.push('        {');
  for (const k of keys) lines.push(`            case ${lit(k)}: return ${lit(cat[k])};`);
  lines.push('            default: return null;');
  lines.push('        }');
  lines.push('    }');
}
lines.push('}');
const text = lines.join('\n') + '\n';

if (check) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== text) {
    console.error('src/Astra.Desktop.Core/I18n/Messages.g.cs is out of date; run `node scripts/gen-desktop-i18n.mjs`.');
    process.exit(1);
  }
  console.log(`Messages.g.cs is up to date (${keys.length} keys).`);
} else {
  writeFileSync(target, text);
  console.log(`wrote ${target} (${keys.length} keys, ${text.length} chars)`);
}
