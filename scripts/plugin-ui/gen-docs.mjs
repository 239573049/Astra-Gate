#!/usr/bin/env node
// The v2 plugin UI component reference (design/plugin-v2 06 §7), generated from the schema (src/Astra.Plugins/V2/Ui/
// components.json) and the scene set (tests/fixtures/plugin-ui): one page per component under
// content/docs/plugin-dev/components/ in the website repository (astra-gate-web, served at astra-gate.si), with its props,
// what it takes as children, where it may be a root, and the default scene's tree as the example (the same tree the gallery
// and the two-shell comparison use). The website is found at $ASTRA_WEB_DIR, else ../astra-gate-web next to this repository.
//
//   node scripts/plugin-ui/gen-docs.mjs           writes the pages and their meta.json into the website
//   node scripts/plugin-ui/gen-docs.mjs --check   fails when they are stale
import { readFileSync, writeFileSync, mkdirSync, rmSync, readdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = dirname(dirname(dirname(fileURLToPath(import.meta.url))));
const schema = JSON.parse(readFileSync(join(repo, 'src/Astra.Plugins/V2/Ui/components.json'), 'utf8'));
const { scenes } = JSON.parse(readFileSync(join(repo, 'src/Astra.Plugins/V2/Ui/scenes.json'), 'utf8'));
const web = resolve(process.env.ASTRA_WEB_DIR || join(repo, '..', 'astra-gate-web'));
if (!existsSync(join(web, 'content', 'docs'))) {
  console.error(
    `website repository not found: ${web} has no content/docs — check out astra-gate-web next to this repository ` +
      'or set ASTRA_WEB_DIR to its path',
  );
  process.exit(2);
}
const out = join(web, 'content/docs/plugin-dev/components');
const check = process.argv.includes('--check');

const GROUPS = [
  ['LayoutGrid', '布局', ['Page', 'Stack', 'Grid', 'Split', 'Scroll', 'Box', 'Divider', 'Spacer', 'Sticky', 'Group', 'Row', 'Card', 'Section', 'Tabs', 'Tab', 'Accordion', 'AccordionItem', 'Disclosure', 'Stepper', 'Timeline', 'Breadcrumb', 'Toolbar', 'Boundary']],
  ['Type', '内容', ['Text', 'Heading', 'RichText', 'Markdown', 'Code', 'JsonView', 'DiffView', 'Link', 'Icon', 'Image', 'Avatar', 'Badge', 'StatusDot', 'Kbd', 'KV', 'Alert', 'Banner', 'EmptyState', 'Skeleton', 'Spinner', 'Progress', 'Meter', 'Counter', 'QRCode']],
  ['MousePointerClick', '操作', ['Button', 'IconButton', 'ButtonGroup', 'SplitButton', 'CopyButton', 'ConfirmButton', 'Menu', 'ContextMenu']],
  ['TextCursorInput', '输入与表单', ['TextField', 'PasswordField', 'TextArea', 'NumberField', 'MoneyField', 'SearchField', 'CodeField', 'Switch', 'Checkbox', 'RadioGroup', 'RadioCards', 'Segmented', 'Select', 'Combobox', 'MultiSelect', 'ChipGroup', 'TagInput', 'Slider', 'DatePicker', 'DateRangePicker', 'TimePicker', 'KeyValueEditor', 'ListEditor', 'FileDrop', 'Form', 'Field', 'FieldGroup']],
  ['Table', '数据', ['Table', 'List', 'Tree', 'Pagination', 'LogView']],
  ['ChartLine', '图表', ['MetricCard', 'Sparkline', 'Chart', 'Heatmap', 'Gauge', 'Canvas']],
  ['PanelRight', '浮层', ['Sheet', 'Dialog', 'Popover']],
  ['Waypoints', 'Astra 专用', ['ModelPicker', 'ProviderPicker', 'AccountPicker', 'ClientPicker', 'TokenPicker', 'ProtocolPicker', 'ModelLabel', 'ProviderLabel', 'ClientLabel', 'Money', 'RequestLink', 'TraceLink', 'UsageBar']],
];

const CHILDREN = { none: '不接受子节点', any: '任意多个子节点', one: '恰好一个子节点', two: '恰好两个子节点', text: '不接受子节点（文字放在 `value`）' };

function typeText(t) {
  if (t.startsWith('enum:')) return t.slice(5).split('|').map((v) => `\`${v}\``).join(' · ');
  if (t.startsWith('token:')) {
    const name = t.slice(6);
    const values = schema.tokens?.[name];
    return values && values.length <= 12 ? values.map((v) => `\`${v}\``).join(' · ') : `${name} 令牌`;
  }
  return { text: '文本', string: '字符串', number: '数字', boolean: '布尔', json: 'JSON', node: '节点', nodes: '节点数组', action: '动作' }[t] ?? t;
}

const escape = (s) => String(s).replace(/\|/g, '\\|');
const slug = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

function page(name, def, group) {
  const scene = scenes.find((s) => s.id === `${name}/default`);
  const states = scenes.filter((s) => s.component === name && s.state !== 'default').map((s) => `\`${s.state}\``);
  const roots = Object.entries(schema.slotRoots ?? {}).filter(([, list]) => list.includes(name)).map(([slot]) => `\`${slot}\``);
  const props = Object.entries(def.props ?? {});
  const lines = [
    '---',
    `title: ${name}`,
    `description: v2 插件界面组件 ${name}（${group}）的属性、子节点与示例`,
    '---',
    '',
    '{/* generated by scripts/plugin-ui/gen-docs.mjs from components.json and the scene set — do not edit */}',
    '',
    `**分组**：${group} · **子节点**：${CHILDREN[def.children ?? 'none'] ?? def.children}${def.input ? ' · **输入组件**：另有[输入属性](/docs/plugin-dev/components#输入属性)' : ''}`,
    '',
  ];
  if (roots.length) lines.push(`可以作为 ${roots.join('、')} 的根节点。`, '');
  lines.push('## 属性', '');
  if (props.length === 0) lines.push('没有自己的属性，只有[通用属性](/docs/plugin-dev/components#通用属性)。', '');
  else {
    lines.push('| 属性 | 类型 |', '| --- | --- |');
    for (const [k, t] of props) lines.push(`| \`${k}\` | ${escape(typeText(t))} |`);
    lines.push('', '另有所有组件都有的[通用属性](/docs/plugin-dev/components#通用属性)。动作类型的属性写动作名，或 `{ action, args }`。', '');
  }
  if (scene) {
    lines.push('## 示例', '', '组件画廊和两端比对用的就是这棵树：', '', '```json', JSON.stringify(scene.tree, null, 2), '```', '');
  }
  if (states.length) lines.push(`画廊里另有这些状态：${states.join('、')}。`, '');
  return lines.join('\n');
}

function index() {
  const lines = [
    '---',
    'title: 组件参考',
    'description: v2 插件界面 1.0 的全部组件，以及每个组件都有的通用属性和输入属性',
    '---',
    '',
    '{/* generated by scripts/plugin-ui/gen-docs.mjs — do not edit */}',
    '',
    `UI 协议版本 \`${schema.version}\`，共 ${Object.keys(schema.components).length} 个组件。每个组件一页：属性、子节点、示例。用 \`ui.<组件名>(props, children)\` 构造，或在 JSX 里写 \`<组件名 />\`。`,
    '',
  ];
  for (const [, group, names] of GROUPS) lines.push(`- **${group}**：${names.map((n) => `[${n}](/docs/plugin-dev/components/${slug(n)})`).join('、')}`);
  lines.push('', '## 通用属性', '', '| 属性 | 类型 |', '| --- | --- |');
  for (const [k, t] of Object.entries(schema.common)) lines.push(`| \`${k}\` | ${escape(typeText(t))} |`);
  lines.push('', '`visible` / `disabled` 可以是布尔，或 `ui.when(...)` 条件（由界面在本地求值）。', '', '## 输入属性', '', '输入组件（文本框、选择、开关、日期等）另有：', '', '| 属性 | 类型 |', '| --- | --- |');
  for (const [k, t] of Object.entries(schema.inputProps)) lines.push(`| \`${k}\` | ${escape(typeText(t))} |`);
  lines.push('', '`name` 是它在本地状态里的键：动作用 `ctx.local[name]` 读取。', '', '## 令牌', '', '| 令牌 | 取值 |', '| --- | --- |');
  for (const [k, v] of Object.entries(schema.tokens ?? {})) lines.push(`| ${k} | ${v.map((x) => `\`${x}\``).join(' · ')} |`);
  lines.push('');
  return lines.join('\n');
}

const files = new Map();
const listed = new Set(GROUPS.flatMap((g) => g[2]));
const unlisted = Object.keys(schema.components).filter((n) => !listed.has(n));
if (unlisted.length) {
  console.error(`components not in a docs group: ${unlisted.join(', ')} — add them to GROUPS in scripts/plugin-ui/gen-docs.mjs`);
  process.exit(1);
}
files.set('index.mdx', index());
const pages = ['index'];
for (const [icon, group, names] of GROUPS) {
  pages.push(`---[${icon}]${group}---`);
  for (const name of names) {
    files.set(`${slug(name)}.mdx`, page(name, schema.components[name], group));
    pages.push(slug(name));
  }
}
files.set('meta.json', JSON.stringify({ title: '组件参考', description: 'v2 插件界面组件', icon: 'Component', defaultOpen: false, pages }, null, 2) + '\n');

if (check) {
  const stale = [...files].filter(([rel, text]) => !existsSync(join(out, rel)) || readFileSync(join(out, rel), 'utf8') !== text).map(([rel]) => rel);
  if (existsSync(out)) for (const f of readdirSync(out)) if (!files.has(f)) stale.push(`${f} (no longer generated)`);
  if (stale.length) {
    console.error(`${out} is stale: ${stale.slice(0, 8).join(', ')} — run node scripts/plugin-ui/gen-docs.mjs`);
    process.exit(1);
  }
  console.log(`component docs are up to date (${files.size - 2} components).`);
} else {
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  for (const [rel, text] of files) writeFileSync(join(out, rel), text);
  console.log(`wrote ${files.size - 2} component pages to ${out}/`);
}
