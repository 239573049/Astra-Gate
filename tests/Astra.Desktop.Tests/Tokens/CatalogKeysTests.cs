    [Fact]
    public void Static_keys_exist() => Assert.All(Static, key => Assert.True(Loc.Has(key), key));

    [Fact]
    public void Dynamic_keys_exist()
    {
        var dynamic = new List<string>();
        dynamic.AddRange(StatsRange.Choices.Select(StatsRange.LabelKey));
        dynamic.AddRange(PoolStrategies.All.SelectMany(s => new[] { PoolStrategies.NameKey(s), PoolStrategies.HintKey(s) }));
        dynamic.AddRange(BudgetRules.Metrics.Select(BudgetRules.MetricKey));
        dynamic.AddRange(BudgetRules.Periods.Select(BudgetRules.PeriodKey));
        dynamic.AddRange(new[] { "healthy", "cooling", "open", "half_open", "no_account", "disabled", "missing" }.Select(s => "tokens.health." + s));
        dynamic.AddRange(new[] { "success", "client_cancelled", "upstream_error", "gateway_error", "blocked", "pending" }.Select(s => "status." + s));
        foreach (var t in new[] { "input", "cache_read", "cache_write_5m", "cache_write_1h", "output", "reasoning", "input_audio", "output_audio", "input_image", "output_image" })
            dynamic.Add(UsageLabels.TokenTypeKey(t)!);
        dynamic.AddRange(new[] { TrendMeasure.CostUsd, TrendMeasure.Requests, TrendMeasure.Tokens }.Select(OverviewShaping.MeasureKey));
        Assert.All(dynamic, key => Assert.True(Loc.Has(key), key));
    }
